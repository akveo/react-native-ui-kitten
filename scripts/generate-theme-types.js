#!/usr/bin/env node
/**
 * Generates the TypeScript view of the theme token names from the theme JSON files:
 *
 * - `src/eva/themes/keys.d.ts` and `src/material/themes/keys.d.ts`: the `EvaThemeKey` /
 *   `MaterialThemeKey` unions and the `EvaTheme` / `MaterialTheme` object types exported by
 *   `@ui-kitten/eva` and `@ui-kitten/material`;
 * - `src/eva/themes/{light,dark}.d.ts` and the Material pair: the per-file declarations for a
 *   direct `require('@ui-kitten/eva/themes/light.json')`;
 * - `src/components/theme/theme/themeKeys.ts`: `KnownThemeKey`, the union of every token the
 *   bundled design systems define, which types `ThemeType`, `useTheme()` and the `useThemeValue`
 *   selectors in `@ui-kitten/components` (with a `string` fallback for custom tokens). It is
 *   generated rather than imported so that `@ui-kitten/components` does not depend on a design
 *   system package for its types.
 *
 * The output is committed. CI reruns this script and fails when the tree changes, so the types
 * always match the JSON. Run `yarn theme-types:generate` after adding or renaming a token.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const HEADER = '// Generated by scripts/generate-theme-types.js from the theme JSON files. Do not edit.\n';

const PACKAGES = [
  { dir: 'src/eva', typePrefix: 'Eva', packageName: '@ui-kitten/eva' },
  { dir: 'src/material', typePrefix: 'Material', packageName: '@ui-kitten/material' },
];
const THEMES = ['light', 'dark'];

const readKeys = (file) => Object.keys(JSON.parse(fs.readFileSync(file, 'utf8')));

const write = (file, content) => {
  fs.writeFileSync(file, content);
  console.log(`wrote ${path.relative(ROOT, file)}`);
};

const unionOf = (keys) => keys.map(key => `  | '${key}'`).join('\n');

const allKeys = new Set();

for (const pkg of PACKAGES) {
  const themesDir = path.join(ROOT, pkg.dir, 'themes');
  const keysByTheme = THEMES.map(theme => readKeys(path.join(themesDir, `${theme}.json`)));
  const [keys] = keysByTheme;
  keysByTheme.forEach((themeKeys, index) => {
    if (JSON.stringify(themeKeys) !== JSON.stringify(keys)) {
      throw new Error(`${pkg.packageName}: themes/${THEMES[index]}.json defines different tokens than themes/light.json`);
    }
  });
  keys.forEach(key => allKeys.add(key));

  for (const theme of THEMES) {
    const body = keys.map(key => `    "${key}": string;`).join('\n');
    write(path.join(themesDir, `${theme}.d.ts`), `declare const _exports: {\n${body}\n};\nexport = _exports;\n`);
  }

  const { typePrefix } = pkg;
  write(path.join(themesDir, 'keys.d.ts'), `${HEADER}
/**
 * Every token name defined by the ${typePrefix} light and dark themes.
 */
export type ${typePrefix}ThemeKey =
${unionOf(keys)};

/**
 * A ${typePrefix} theme: every known token, plus any custom token added by an app.
 */
export type ${typePrefix}Theme = { [K in ${typePrefix}ThemeKey]: string } & { [token: string]: string };
`);
}

write(path.join(ROOT, 'src/components/theme/theme/themeKeys.ts'), `${HEADER}
/**
 * Token names defined by the bundled design systems (Eva and Material). \`ThemeType\` keeps a
 * \`string\` index signature on top of these, so custom tokens still type-check.
 */
export type KnownThemeKey =
${unionOf([...allKeys])};
`);
